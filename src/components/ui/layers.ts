/**
 * 浮层层级。数字越大越靠上。
 *
 * 四层各管一件事，从下到上：
 *
 * - `popover`  锚在控件旁的小面板：下拉、地址来源、变量提示。
 * - `contextMenu`  右键菜单。
 * - `tooltip`  悬浮提示。
 * - `modal`  模态对话框与命令面板。
 *
 * 模态在最高层，理由是模态打开时背景不可操作：背景上的提示气泡若浮在遮罩之上，
 * 会被读成「遮罩没盖住」。模态打开时背景被置为 `inert`，背景的提示气泡根本不会
 * 触发（`inert` 元素不是命中测试的目标），所以两层之间没有实际冲突。
 *
 * 代价要写清楚：**模态面板内部不放提示气泡**。提示层在模态之下，放在模态里的气泡
 * 会被面板盖住。日后要在模态里放气泡时，给提示单独加一层并让模态内的气泡用它，
 * 不要靠调 `z-index` 解决。
 */

export const LAYER = {
  popover: 'z-50',
  contextMenu: 'z-[60]',
  tooltip: 'z-[70]',
  modal: 'z-[100]',
} as const;
