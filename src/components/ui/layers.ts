/**
 * 浮层层级。数字越大越靠上。
 *
 * 四层各管一件事，从下到上：
 *
 * - `popover`  锚在控件旁的小面板：下拉、地址来源、变量提示。
 * - `contextMenu`  右键菜单。
 * - `tooltip`  悬浮提示。
 * - `modal`  模态对话框与命令面板。
 *
 * 模态在最高层，理由是模态打开时背景不可操作：背景上的提示气泡若浮在遮罩之上，
 * 会被读成「遮罩没盖住」。模态打开时背景被置为 `inert`，背景的提示气泡根本不会
 * 触发（`inert` 元素不是命中测试的目标），所以两层之间没有实际冲突。
 *
 * 模态里的提示气泡是另一层（`tooltipInModal`，110）。提示气泡 portal 到 body，
 * 而模态遮罩也铺满视口 —— 气泡若停在模态之下，就被遮罩盖住。`Tooltip` 组件按触发元素
 * 是否落在 `[data-modal-surface]` 里选层：模态内的气泡用 110，背景的气泡用 70。
 *
 * 背景的气泡停在模态之下是对的：模态打开时背景被置为 `inert`，背景的气泡根本不会
 * 触发；而万一有一个已经显示出来的，它会落在遮罩之下（被压暗），不会浮在对话框上面。
 */

export const LAYER = {
  popover: 'z-50',
  contextMenu: 'z-[60]',
  tooltip: 'z-[70]',
  modal: 'z-[100]',
  /** 模态面板**内部**的提示气泡。它在模态之上，否则会被面板盖住。 */
  tooltipInModal: 'z-[110]',
} as const;
